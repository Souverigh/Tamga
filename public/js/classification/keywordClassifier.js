// Классификация документа по ключевым словам — офлайн-режим (без Gemini).
// Независимый модуль: не знает ничего про извлечение полей (см. extraction/) —
// только определяет тип документа по тексту, уже распознанному OCR.
// Заведомо менее надёжна, чем классификация Gemini, т.к. Tesseract не понимает
// смысл текста — только буквы.

const RULES = [
  { type: 'Паспорт / удостоверение личности', keywords: ['паспорт', 'жеке күбөлүк', 'id card', 'паспорттук'] },
  { type: 'Свидетельство о рождении', keywords: ['свидетельство о рождении', 'туулгандыгы жөнүндө'] },
  { type: 'Свидетельство о браке', keywords: ['свидетельство о заключении брака', 'никеге туруу'] },
  { type: 'Диплом / аттестат', keywords: ['диплом', 'аттестат', 'квалификация', 'выпускник'] },
  { type: 'Справка', keywords: ['справка', 'маалымкат'] },
  { type: 'Договор', keywords: ['договор', 'келишим', 'стороны настоящего'] },
  { type: 'Банковский документ', keywords: ['iban', 'выписка по счёту', 'лицевой счёт', 'реквизиты'] },
  { type: 'Квитанция / чек', keywords: ['квитанция', 'итого к оплате', 'чек №'] },
];

export function classifyByKeywords(text) {
  const t = text.toLowerCase();
  let best = null, bestScore = 0;
  for (const rule of RULES) {
    const score = rule.keywords.reduce((n, kw) => n + (t.includes(kw) ? 1 : 0), 0);
    if (score > bestScore) { bestScore = score; best = rule.type; }
  }
  return best || 'Не определено';
}
